/**
 * The Cetele mark, "the last bead" (D88): a bold open C, for Cetele, with one
 * orange bead in its gap. The bead is the final count that closes the circle,
 * the moment the group finishes its cetele together.
 *
 * This file is the mark's ONLY geometry. Every brand asset is drawn from it by
 * satori (layout) + resvg (rasterising), never edited by hand:
 *
 *   node scripts/gen-icons.mjs    public/logo.svg, logo-tile.svg, PWA icons
 *   node scripts/gen-splash.mjs   the iOS launch images
 *
 * Then bump CACHE in public/sw.js: none of those filenames are content-hashed.
 *
 * Geometry on a 100-unit grid, centred on (50, 50):
 *   C     ring radius 32, stroke 18, round caps, from 130° to 410° clockwise
 *         from twelve o'clock, so the opening is centred on three o'clock.
 *   bead  radius 9, on the ring at three o'clock (82, 50).
 * Outer extent is 41 units from the centre on every side, so the mark is
 * optically centred in any square it is placed in.
 */
export const BLUE = "#0163ad"; // Youth Nexus blue: BRAND_THEME_COLOR / --primary
export const ORANGE = "#f09a3e"; // Youth Nexus orange, --accent
export const WHITE = "#ffffff";

const R = 32;
const STROKE = 18;
const BEAD = 9;
const at = (deg) => {
  const a = ((deg - 90) * Math.PI) / 180;
  return [50 + R * Math.cos(a), 50 + R * Math.sin(a)].map((n) => +n.toFixed(2));
};
const [x0, y0] = at(130);
const [x1, y1] = at(410);
const C_PATH = `M${x0} ${y0} A${R} ${R} 0 1 1 ${x1} ${y1}`;

/** The mark as satori elements, scaled into a `size`-px square. */
export function markElement(size, { ring = BLUE, bead = ORANGE } = {}) {
  return {
    type: "svg",
    props: {
      viewBox: "0 0 100 100",
      width: size,
      height: size,
      children: [
        {
          type: "path",
          props: {
            d: C_PATH,
            fill: "none",
            stroke: ring,
            strokeWidth: STROKE,
            strokeLinecap: "round",
          },
        },
        { type: "circle", props: { cx: 82, cy: 50, r: BEAD, fill: bead } },
      ],
    },
  };
}

/** The mark as a standalone SVG document (what public/logo.svg holds). The
 *  viewBox is cropped to the mark's extent plus a little air. */
export function markSvg({ ring = BLUE, bead = ORANGE } = {}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="6 6 88 88">
  <!-- The Cetele mark (D88). Generated by scripts/gen-icons.mjs from scripts/brand-mark.mjs; do not edit by hand. -->
  <path d="${C_PATH}" fill="none" stroke="${ring}" stroke-width="${STROKE}" stroke-linecap="round"/>
  <circle cx="82" cy="50" r="${BEAD}" fill="${bead}"/>
</svg>
`;
}
